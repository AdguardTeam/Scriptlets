import { hit } from './hit';
import { logMessage } from './log-message';
import { matchRequestProps } from './match-request-props';
import { getXhrData, type XMLHttpRequestSharedRequestData } from './request-utils';
import { objectToString, generateResponseContent } from './string-utils';
import { parseUboPropsToMatch, matchUboProps } from './ubo-request-utils';
import { generateUboContent } from './ubo-utils';
import { getRegexpTester } from './regexp-utils';
import { type Source } from '../scriptlets';

/**
 * Settings of `preventXhrBySettings()`, which are parsed from the arguments of `prevent-xhr`
 * or `trusted-prevent-xhr` once, by `getAdgPreventXhrSettings()` or `getUboPreventXhrSettings()`.
 */
export interface PreventXhrSettings {
    /**
     * If true, requests are logged and not prevented.
     */
    shouldLogRequests: boolean;

    /**
     * Checks whether the request, i.e. the arguments of `open()`, is prevented.
     */
    isRequestMatched: (xhrData: XMLHttpRequestSharedRequestData<any>) => boolean;

    /**
     * Returns the text of the response of a request with an empty `responseType` or `text`.
     */
    getText: () => string;

    /**
     * Returns the text which is parsed as the response of a request with `json` as `responseType`.
     */
    getJsonText: () => string;

    /**
     * Returns the response headers, as pairs of a lowercase name and a value, for the response type
     * and the response, which are available once the request has `HEADERS_RECEIVED` state, as in uBO,
     * or `null` to return the request headers which the page has set as the response headers, as before.
     */
    getResponseHeaders: ((responseType: XMLHttpRequestResponseType, response: unknown) => string[][]) | null;
}

/**
 * Parses the arguments of AdGuard `prevent-xhr` or `trusted-prevent-xhr` as before:
 * - requests are logged if `propsToMatch` is omitted;
 * - `propsToMatch` is matched by `matchRequestProps()` against the arguments of `open()`;
 * - the response is generated by `generateResponseContent()`, and the one of `json` as `responseType`
 *   is parsed from it, or `{}` without a directive.
 *
 * Requires `matchRequestProps` and `generateResponseContent`, with their dependencies,
 * in the injections of the scriptlet.
 *
 * @param source Scriptlet properties.
 * @param propsToMatch Properties of the request to match, or `undefined` to log requests.
 * @param directive Directive of the response content.
 * @param isTrusted If true, as for `trusted-prevent-xhr`, a directive which is not a keyword is the content as it is.
 *
 * @returns Settings of the rule.
 */
export const getAdgPreventXhrSettings = (
    source: Source,
    propsToMatch: string | undefined,
    directive: string | undefined,
    isTrusted: boolean,
): PreventXhrSettings => {
    // !IMPORTANT: Do not move constants outside of this function
    const DEFAULT_JSON_TEXT = '{}';

    /**
     * Generates the content of the directive, which is generated again for each request, e.g. a random one.
     *
     * @param defaultContent Content without a directive, or of an invalid one, which is logged.
     * @returns Content of the response.
     */
    const getContent = (defaultContent: string): string => {
        if (!directive) {
            return defaultContent;
        }
        const content = generateResponseContent(directive, isTrusted);
        if (content === null) {
            logMessage(source, `Invalid randomize parameter: '${directive}'`);
            return defaultContent;
        }
        return content;
    };

    return {
        shouldLogRequests: typeof propsToMatch === 'undefined',
        isRequestMatched: (xhrData) => matchRequestProps(source, propsToMatch as string, xhrData),
        getText: () => getContent(''),
        getJsonText: () => getContent(DEFAULT_JSON_TEXT),
        getResponseHeaders: null,
    };
};

/**
 * Parses the arguments of uBO `prevent-xhr.js` or `trusted-prevent-xhr.js`, converted to AdGuard syntax,
 * as uBO `preventXhrFn()` does:
 * - requests are logged if both `propsToMatch` and the directive are empty, and all requests are prevented
 *   if only `propsToMatch` is empty;
 * - `propsToMatch` is matched as uBO does, see `parseUboPropsToMatch()`, against the method and the URL
 *   of `open()`, which is the implicit property;
 * - the response is generated as uBO does, see `generateUboContent()`, and the one of `json` as `responseType`
 *   is always `{}`;
 * - the response headers are `date`, `content-type` of the response type and `content-length`.
 *
 * Unlike uBO, which throws, a rule with an invalid regular expression in `propsToMatch` is logged.
 *
 * Requires `logMessage`, `parseUboPropsToMatch`, `matchUboProps`, `getRegexpTester`, `getNativeRegexpTest`
 * and `generateUboContent` in the injections of the scriptlet.
 *
 * @param source Scriptlet properties.
 * @param propsToMatch Properties of the request to match, e.g. `/ads/ method:POST`.
 * @param directive Directive of the response content.
 * @param isTrusted If true, as for `trusted-prevent-xhr.js`, a directive which is not a keyword
 * is the content as it is.
 *
 * @returns Settings of the rule, or `null` if `propsToMatch` is invalid.
 */
export const getUboPreventXhrSettings = (
    source: Source,
    propsToMatch: unknown,
    directive: unknown,
    isTrusted: boolean,
): PreventXhrSettings | null => {
    // !IMPORTANT: Do not move constants outside of this function
    const IMPLICIT_PROP = 'url';
    const JSON_TEXT = '{}';
    const CONTENT_TYPES: Record<string, string> = {
        arraybuffer: 'application/octet-stream',
        blob: 'application/octet-stream',
        document: 'text/html',
        json: 'application/json',
    };
    const TEXT_CONTENT_TYPE = 'text/plain';

    const props = typeof propsToMatch === 'string' ? propsToMatch : '';
    const content = typeof directive === 'string' ? directive : '';

    const needles = parseUboPropsToMatch(props, IMPLICIT_PROP);
    if (needles === null) {
        logMessage(source, `Invalid propsToMatch: '${props}'`);
        return null;
    }
    const testRegexp = getRegexpTester();

    return {
        shouldLogRequests: props === '' && content === '',
        // As in uBO, only the method and the URL as they are passed to `open()` are matched
        isRequestMatched: (xhrData) => matchUboProps(
            needles,
            { method: xhrData.method, url: xhrData.url },
            testRegexp,
        ),
        getText: () => (content === '' ? '' : generateUboContent(content, isTrusted)),
        getJsonText: () => JSON_TEXT,
        getResponseHeaders: (responseType, response) => {
            let contentType = '';
            if (Object.prototype.hasOwnProperty.call(CONTENT_TYPES, responseType)) {
                contentType = CONTENT_TYPES[responseType];
            } else if (content !== '') {
                contentType = TEXT_CONTENT_TYPE;
            }
            // As in uBO, the length is the one of the response converted to a string, e.g. of `{}` as an object,
            // and headers with an empty value or a zero length are not returned
            const length = `${response}`.length;
            return [
                ['date', new Date().toUTCString()],
                ['content-type', contentType],
                ['content-length', length === 0 ? '' : `${length}`],
            ].filter((header) => header[1] !== '');
        },
    };
};

/**
 * Sets up XMLHttpRequest interception to prevent matched requests from
 * reaching the network, substituting a generated response,
 * by the settings parsed by `getAdgPreventXhrSettings()` or `getUboPreventXhrSettings()`.
 *
 * Requires `hit`, `logMessage`, `getXhrData` and `objectToString`, with their dependencies,
 * in the injections of the scriptlet.
 *
 * @param source Scriptlet source object for hit/logging.
 * @param settings Settings of the rule.
 */
export function preventXhrBySettings(source: Source, settings: PreventXhrSettings): void {
    // do nothing if browser does not support Proxy (e.g. Internet Explorer)
    // https://developer.mozilla.org/en-US/docs/Web/JavaScript/Reference/Global_Objects/Proxy
    if (typeof Proxy === 'undefined') {
        return;
    }

    const nativeOpen: any = window.XMLHttpRequest.prototype.open;
    const nativeGetResponseHeader: any = window.XMLHttpRequest.prototype.getResponseHeader;
    const nativeGetAllResponseHeaders: any = window.XMLHttpRequest.prototype.getAllResponseHeaders;

    // Store matched XHR requests and their data in private structures
    // to prevent bypass via thisArg property manipulation
    // https://github.com/AdguardTeam/Scriptlets/issues/386
    const matchedXhrRequests = new Map();
    const xhrRequestHeaders = new Map();
    // Response headers of the settings, e.g. of uBO rules, by the requests, which are not kept alive by it
    const xhrResponseHeaders = new WeakMap<XMLHttpRequest, string[][]>();
    // Value of `readyState` once the response headers have been received, i.e. `XMLHttpRequest.HEADERS_RECEIVED`.
    // `readyState` is 0 (UNSENT), 1 (OPENED), 2 (HEADERS_RECEIVED), 3 (LOADING) or 4 (DONE), see
    // https://developer.mozilla.org/en-US/docs/Web/API/XMLHttpRequest/readyState
    // As in uBO, the response headers of the settings are returned only from this state on, while before it
    // the native method is called, which returns no headers, as for a request which has not received them yet.
    // The number is used instead of `XMLHttpRequest.HEADERS_RECEIVED`, as the hooks read it when the page calls
    // them, and the page may have replaced `XMLHttpRequest` by then, e.g. with its own class without the constant.
    const HEADERS_RECEIVED = 2;

    const openWrapper = (
        target: any,
        thisArg: any,
        args: any[],
    ): any => {
        // Get original request properties
        // eslint-disable-next-line prefer-spread
        const xhrData: any = getXhrData.apply(null, args as any);

        if (settings.shouldLogRequests) {
            // Log if no propsToMatch given
            logMessage(source, `xhr( ${objectToString(xhrData)} )`, true);
            hit(source);
        } else if (settings.isRequestMatched(xhrData)) {
            // First stage of the request lifecycle should be fired only if onreadystatechange is assigned
            // https://github.com/AdguardTeam/Scriptlets/issues/485
            if (typeof thisArg.onreadystatechange === 'function') {
                xhrData.shouldFireFirstStage = true;
            }
            // Store xhrData in map to keep original values in case of multiple requests
            // https://github.com/AdguardTeam/Scriptlets/issues/347
            matchedXhrRequests.set(thisArg, xhrData);
        }

        // Trap setRequestHeader of target xhr object to mimic request headers later;
        // needed for getResponseHeader() and getAllResponseHeaders() methods
        if (
            settings.getResponseHeaders === null
            && matchedXhrRequests.has(thisArg)
            && !xhrRequestHeaders.has(thisArg)
        ) {
            xhrRequestHeaders.set(thisArg, []);
            const setRequestHeaderWrapper = (t: any, thisArg2: any, a: any[]): any => {
                // Collect headers
                const headers = xhrRequestHeaders.get(thisArg2);
                if (headers) {
                    headers.push(a);
                }
                return Reflect.apply(t, thisArg2, a);
            };
            const setRequestHeaderHandler = {
                apply: setRequestHeaderWrapper,
            };
            // setRequestHeader() can only be called on xhr.open(),
            // so we can safely proxy it here
            thisArg.setRequestHeader = new Proxy(thisArg.setRequestHeader, setRequestHeaderHandler);
        }
        return Reflect.apply(target, thisArg, args);
    };

    const sendWrapper = (target: any, thisArg: any, args: any[]): any => {
        if (!matchedXhrRequests.has(thisArg)) {
            return Reflect.apply(target, thisArg, args);
        }

        const storedXhrData = matchedXhrRequests.get(thisArg);

        const responseType = thisArg.responseType;

        let modifiedResponse: any = '';
        let modifiedResponseText = '';
        let modifiedResponseXML: any;

        // Whether responseText is accessible for this responseType.
        // Native XHR throws InvalidStateError when responseText is accessed
        // with any responseType other than '' or 'text' (including 'json',
        // 'blob', 'arraybuffer', and 'document').
        // https://developer.mozilla.org/en-US/docs/Web/API/XMLHttpRequest/responseText
        let exposeResponseText = true;

        if (responseType === 'blob') {
            modifiedResponse = new Blob();
            exposeResponseText = false;
        } else if (responseType === 'arraybuffer') {
            modifiedResponse = new ArrayBuffer(0);
            exposeResponseText = false;
        } else if (responseType === 'document') {
            modifiedResponse = new DOMParser().parseFromString('', 'text/html');
            modifiedResponseXML = modifiedResponse;
            exposeResponseText = false;
        } else if (responseType === 'json') {
            // For json responseType, response is the parsed JSON object (or
            // null if the text is not valid JSON). Accessing responseText with
            // responseType 'json' throws InvalidStateError in native XHR
            // (Chromium included), so we do NOT expose it for the JSON branch.
            // Trusted directives can pass a literal JSON string (e.g.
            // '{"blocked":true}') that gets parsed and exposed as a parsed
            // object via response.
            exposeResponseText = false;
            try {
                modifiedResponse = JSON.parse(settings.getJsonText());
            } catch {
                // Invalid JSON → response is null, matching native XHR behavior
                modifiedResponse = null;
            }
        } else {
            modifiedResponse = settings.getText();
            modifiedResponseText = modifiedResponse;
        }

        if (settings.getResponseHeaders !== null) {
            xhrResponseHeaders.set(thisArg, settings.getResponseHeaders(responseType, modifiedResponse));
        }

        /**
         * Create separate XHR request with original request's input
         * to be able to collect response data without triggering
         * listeners on original XHR object
         */
        const forgedRequest = new XMLHttpRequest();

        /**
         * Used to manually simulate the progression of the readyState property.
         * By using Object.defineProperty, the function ensures
         * that the readyState can be modified and configured appropriately,
         * while allowing the property to be writable.
         *
         * @param state request status number.
         */
        const transitionReadyState = (state: number): void => {
            // For readyState 2, we need to set responseURL
            // https://github.com/AdguardTeam/Scriptlets/issues/485
            if (state === 2) {
                const { responseURL } = forgedRequest;
                Object.defineProperties(thisArg, {
                    responseURL: { value: responseURL || storedXhrData.url, writable: false },
                });
            }

            if (state === 4) {
                const { responseXML } = forgedRequest;

                // Use the generated responseXML for 'document' responseType,
                // otherwise fall back to the forged request's value (null)
                const finalResponseXML = typeof modifiedResponseXML !== 'undefined'
                    ? modifiedResponseXML
                    : responseXML;

                // Mock response object. Only expose responseText for
                // responseTypes where it is accessible in native XHR.
                // For 'blob', 'arraybuffer', and 'document' the native getter
                // throws InvalidStateError, so we leave it untouched.
                const mockProps: PropertyDescriptorMap = {
                    readyState: { value: 4, writable: false },
                    statusText: { value: 'OK', writable: false },
                    responseXML: { value: finalResponseXML, writable: false },
                    status: { value: 200, writable: false },
                    response: { value: modifiedResponse, writable: false },
                };
                if (exposeResponseText) {
                    mockProps.responseText = { value: modifiedResponseText, writable: false };
                }
                Object.defineProperties(thisArg, mockProps);
                hit(source);
            } else {
                Object.defineProperty(thisArg, 'readyState', {
                    value: state,
                    writable: true,
                    configurable: true,
                });
            }
            const stateEvent = new Event('readystatechange');
            thisArg.dispatchEvent(stateEvent);
        };

        // All events added to avoid problems with anti-adblockers
        // https://github.com/AdguardTeam/Scriptlets/issues/414
        forgedRequest.addEventListener('readystatechange', () => {
            // simulate the lifecycle
            if (matchedXhrRequests.get(thisArg).shouldFireFirstStage) {
                transitionReadyState(1);
            }
            const loadStartEvent = new ProgressEvent('loadstart');
            thisArg.dispatchEvent(loadStartEvent);
            transitionReadyState(2);
            transitionReadyState(3);
            const progressEvent = new ProgressEvent('progress');
            thisArg.dispatchEvent(progressEvent);
            transitionReadyState(4);
        });

        setTimeout(() => {
            const loadEvent = new ProgressEvent('load');
            thisArg.dispatchEvent(loadEvent);
            const loadEndEvent = new ProgressEvent('loadend');
            thisArg.dispatchEvent(loadEndEvent);
        }, 1);

        nativeOpen.apply(forgedRequest, [storedXhrData.method, storedXhrData.url]);

        // Mimic request headers before sending
        // setRequestHeader can only be called on open request objects
        const collectedHeaders = xhrRequestHeaders.get(thisArg) || [];
        collectedHeaders.forEach((header: any) => {
            const name = header[0];
            const value = header[1];
            forgedRequest.setRequestHeader(name, value);
        });
        // Note: We do NOT delete from xhrRequestHeaders here because
        // getResponseHeader() and getAllResponseHeaders() need access to the headers later

        return undefined;
    };

    /**
     * Mock XMLHttpRequest.prototype.getResponseHeader() to avoid adblocker detection.
     *
     * @param target Native `getResponseHeader` method.
     * @param thisArg The request.
     * @param args Header name is passed as first argument.
     *
     * @returns Header value or null if header is not set.
     */
    const getHeaderWrapper = (target: any, thisArg: any, args: any[]): any => {
        const responseHeaders = xhrResponseHeaders.get(thisArg);
        if (responseHeaders) {
            if (thisArg.readyState < HEADERS_RECEIVED) {
                return nativeGetResponseHeader.apply(thisArg, args);
            }
            const name = `${args[0]}`.toLowerCase();
            const header = responseHeaders.find((item) => item[0] === name);
            return header ? header[1] : null;
        }

        const collectedHeaders = xhrRequestHeaders.get(thisArg);
        if (!collectedHeaders) {
            return nativeGetResponseHeader.apply(thisArg, args);
        }
        if (!collectedHeaders.length) {
            return null;
        }
        // The search for the header name is case-insensitive
        // https://developer.mozilla.org/en-US/docs/Web/API/XMLHttpRequest/getResponseHeader
        const searchHeaderName = args[0].toLowerCase();
        const matchedHeader = collectedHeaders.find((header: any) => {
            const headerName = header[0].toLowerCase();
            return headerName === searchHeaderName;
        });
        return matchedHeader
            ? matchedHeader[1]
            : null;
    };

    /**
     * Mock XMLHttpRequest.prototype.getAllResponseHeaders() to avoid adblocker detection.
     *
     * @param target Native `getAllResponseHeaders` method.
     * @param thisArg The request.
     *
     * @returns All headers as a string. For no headers an empty string is returned.
     */
    const getAllHeadersWrapper = (target: any, thisArg: any): any => {
        const responseHeaders = xhrResponseHeaders.get(thisArg);
        if (responseHeaders) {
            if (thisArg.readyState < HEADERS_RECEIVED) {
                return nativeGetAllResponseHeaders.call(thisArg);
            }
            // Each header is followed by CRLF, as in native responses
            return responseHeaders.map((header) => `${header[0]}: ${header[1]}\r\n`).join('');
        }

        const collectedHeaders = xhrRequestHeaders.get(thisArg);

        if (!collectedHeaders) {
            return nativeGetAllResponseHeaders.call(thisArg);
        }

        if (!collectedHeaders.length) {
            return '';
        }

        const allHeadersStr = collectedHeaders
            .map((header: any) => {
                /**
                 * TODO: array destructuring may be used here
                 * after the typescript implementation and bundling refactoring
                 * as now there is an error: slicedToArray is not defined
                 */
                const headerName = header[0];
                const headerValue = header[1];
                // In modern browsers, the header names are returned in all lower case, as per the latest spec.
                // https://developer.mozilla.org/en-US/docs/Web/API/XMLHttpRequest/getAllResponseHeaders
                return `${headerName.toLowerCase()}: ${headerValue}`;
            })
            .join('\r\n');
        return allHeadersStr;
    };

    const openHandler = {
        apply: openWrapper,
    };
    const sendHandler = {
        apply: sendWrapper,
    };
    const getHeaderHandler = {
        apply: getHeaderWrapper,
    };
    const getAllHeadersHandler = {
        apply: getAllHeadersWrapper,
    };

    XMLHttpRequest.prototype.open = new Proxy(XMLHttpRequest.prototype.open, openHandler);
    XMLHttpRequest.prototype.send = new Proxy(XMLHttpRequest.prototype.send, sendHandler);
    XMLHttpRequest.prototype.getResponseHeader = new Proxy(
        XMLHttpRequest.prototype.getResponseHeader,
        getHeaderHandler,
    );
    XMLHttpRequest.prototype.getAllResponseHeaders = new Proxy(
        XMLHttpRequest.prototype.getAllResponseHeaders,
        getAllHeadersHandler,
    );
}
